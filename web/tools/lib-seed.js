// 판정기 공용 — **씬 전체를 재현 가능하게 만든다** (slug: uniform-outline-postfx, 2026-08-25 3D 스트림).
//
// 🚨 왜 필요한가: 지금까지 판정기들은 `Scene3D._clock = 0` 과 리그 `_t = 0` 으로 위상을 고정했다.
//    그런데 조형 하나하나가 **자기 위상을 따로 들고 있다** — `g.userData.phase = U.rand(0, 2π)`
//    (탈것 `scene3d.js:10657` · 펫 `:9541` · 적 무리 `:10728` · 배경 소품 `:1588`). 이건 **오브젝트가
//    만들어질 때** 정해지므로 `_clock` 을 아무리 0 으로 눌러도 안 덮인다. 탈것 상하 바운스가
//    `abs(sin((_clock + phase) * 4)) * 0.05` 라, 위상이 다르면 **탈것이 서는 높이가 런마다 다르다**.
//
//    실측(2026-08-25, 같은 커밋·같은 셰이더로 `probe-crease-lines.js` 연속 실행):
//      mountY 0.0180 / 0.0256 / 0.0401 … → 발굽↔지면 **열커버 22% ↔ 72%** 로 튀었다.
//      → 과거 TODO 에 적힌 "접지선 67~71%" 와 "22%" 는 **셰이더 차이가 아니라 이 위상 차이**였다.
//    분포를 보는 자(strata)는 이 흔들림을 평균으로 덮지만, **특정 경계 한 줄을 보는 자는 못 덮는다.**
//
// 🧭 그래서 위상을 하나씩 쫓아다니며 0 으로 누르지 않는다(`phase` 는 링 배치처럼 **일부러 어긋나게**
//    둔 자리도 있어서, 전부 0 으로 만들면 조형 자체가 바뀐다). 대신 **씬이 만들어지기 전에
//    `Math.random` 을 결정론적 PRNG 로 갈아 끼운다** — 그러면 `U.rand` 를 쓰는 모든 자리가
//    (위상·산포·지형 스캐터까지) 매 런 똑같은 값을 받아 **같은 씬**이 나온다.
//
// 사용:
//   const { SEED_INIT } = require('./lib-seed');
//   await page.addInitScript(SEED_INIT);      // ← page.goto 보다 **먼저** 부를 것
//
// ⚠️ `addInitScript` 는 페이지 스크립트보다 먼저 돈다 — 그래서 `util.js` 의 `U.rand` 가
//    정의되기 전에 `Math.random` 이 이미 갈려 있다. goto 뒤에 부르면 아무 효과가 없다.
const SEED_INIT = `(() => {
  let s = 0x2f6e2b1 >>> 0;                       // xorshift32 — 상태 1워드, 브라우저 의존 0
  Math.random = () => {
    s ^= s << 13; s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5;  s >>>= 0;
    return s / 4294967296;
  };
})()`;

module.exports = { SEED_INIT };
