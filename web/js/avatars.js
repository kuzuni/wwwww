    /* 칸 경계를 반올림으로 잡아 이웃 칸과 **정확히 맞물리게** 한다. 폭을 소수로 그리면
       칸 사이에 반투명 실선이 생겨 흰 타일 위에서 격자 자국으로 보인다. */
    function paint(ctx, S, g) {
        const e = i => Math.round(i * S / N);
        for (let j = 0; j < N; j++) {
            const y0 = e(j), y1 = e(j + 1);
            for (let i = 0; i < N; i++) {
                const c = g[j][i];
                if (!c) continue;
                const x0 = e(i), x1 = e(i + 1);
                ctx.fillStyle = c;
                ctx.fillRect(x0, y0, x1 - x0, y1 - y0);
            }
        }
    }

