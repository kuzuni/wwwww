            R(g, 22, 27, 2, 5, P.ink2); D(g, P.ink2, [21, 26], [23, 26]);  // 마이크 손잡이
            E(g, 21, 24, 3, 3, P.greyDk);                      // 마이크 헤드(턱 옆 흰 여백 위)
